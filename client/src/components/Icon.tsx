interface IconProps {
  name: IconName;
  size?: number;
  strokeWidth?: number;
  className?: string;
  style?: import('react').CSSProperties;
}

export function Icon({ name, size = 24, strokeWidth = 1.8, className, style }: IconProps) {
  const filled = FILLED.has(name);
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill={filled ? 'currentColor' : 'none'}
      stroke={filled ? 'none' : 'currentColor'}
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      style={style}
      aria-hidden="true"
    >
      {PATHS[name]}
    </svg>
  );
}

/** Wiederholt ein Stern-Icon `count`-mal (ersetzt ⭐-Emojis in Listen). */
export function Stars({ count, size = 14 }: { count: number; size?: number }) {
  if (count <= 0) return null;
  return (
    <span className="inline-flex items-center gap-0.5 align-middle text-(--color-warning)">
      {Array.from({ length: count }).map((_, i) => (
        <Icon key={i} name="star" size={size} />
      ))}
    </span>
  );
}
